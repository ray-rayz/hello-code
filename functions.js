// A function that takes input (a name) and returns output (a greeting).
function greet(name) {
  return `Hello, ${name}!`;
}

//The same idea as an arrow function.
const double = (n) => n * 2;

//A function with two output.
function add(a, b) {
  return a + b;
}

console.log(greet("Ray"));
console.log(double(21));
console.log(add(5, 7));
