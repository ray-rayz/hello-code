// A function that outputs a square of an input
function square(n) {
  return n * n;
}

// Boolean function.
function isAdult(age) {
   return age >= 18;
}

// A function tha outputs full names.
function fullName(first, last) {
  return `${first} ${last}`;
}

console.log(square(9));
console.log(isAdult(20));
console.log(fullName("Ray", "Smith"));
